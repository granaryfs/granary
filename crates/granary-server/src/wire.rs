/// The cache directive §6 fixes for a response.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CacheControl {
    /// A year, and no revalidation inside it. The representation cannot
    /// change: its identity is its hash.
    Immutable,
    /// A publish can make a cached `max-seq` response stale. Authority responses also use
    /// `no-store` for submission results, volume status and intent state.
    NoStore,
    /// The hint may be reused only after successful revalidation. The
    /// freshness lifetime is zero, deliberately: the `ETag` is what makes
    /// the poll cheap, so a window buys nothing.
    NoCache,
}

impl CacheControl {
    /// The directive's spelling on the wire (§6).
    ///
    /// The immutable form carries `max-age` and `immutable` and nothing
    /// else: §6 forbids `public`, `s-maxage` and `must-revalidate` on a
    /// bin response outright.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Immutable => "max-age=31536000, immutable",
            Self::NoStore => "no-store",
            Self::NoCache => "no-cache",
        }
    }
}

/// The four method sets advertised by [`Resource::allow`] on a `405`.
/// RFC 9110 §15.5.6 requires the response to list the target's supported
/// methods. None of these resources supports `HEAD`.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Allow {
    /// Registration and principal-scoped control read.
    GetPost,
    /// A bin, a meta object, a numbered root, and the hint.
    GetPut,
    /// `max-seq` and the volume status, which are read-only.
    Get,
    /// Publish, intent release and intent ownership.
    Post,
}

impl Allow {
    /// The field value's spelling on the wire (§4.2).
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::GetPost => "GET, POST",
            Self::GetPut => "GET, PUT",
            Self::Get => "GET",
            Self::Post => "POST",
        }
    }
}

/// A parsed request target. Five resources address the store. The authority
/// handles publish, volume status and the three intent resources.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Resource {
    /// Registration and readback.
    Intent,
    /// Release.
    IntentRelease,
    /// Ownership acquire/takeover.
    IntentOwnership,
    /// `{base}/bin/{digest}`.
    Bin,
    /// `{base}/volume/{volume}/meta/{grain-id}`.
    Meta,
    /// `{base}/volume/{volume}/root/{seq}`.
    Root,
    /// `{base}/volume/{volume}/max-seq`.
    MaxSeq,
    /// `{base}/volume/{volume}/hint`.
    Hint,
    /// `{base}/volume/{volume}/publish`.
    Publish,
    /// `{base}/volume/{volume}/status`.
    VolumeStatus,
}

impl Resource {
    /// The target's supported methods, advertised on a `405`. For example,
    /// a write to `max-seq` must advertise only `GET`.
    #[must_use]
    pub const fn allow(self) -> Allow {
        match self {
            Self::Bin | Self::Meta | Self::Root | Self::Hint => Allow::GetPut,
            Self::MaxSeq | Self::VolumeStatus => Allow::Get,
            Self::Intent => Allow::GetPost,
            Self::IntentRelease | Self::IntentOwnership | Self::Publish => Allow::Post,
        }
    }

    /// The cache directive for a `405` on this resource. Authority resources
    /// require `no-store`. Store resources omit the field.
    #[must_use]
    pub const fn refusal_cache_control(self) -> Option<CacheControl> {
        match self {
            Self::Bin | Self::Meta | Self::Root | Self::MaxSeq | Self::Hint => None,
            Self::Intent
            | Self::IntentRelease
            | Self::IntentOwnership
            | Self::Publish
            | Self::VolumeStatus => Some(CacheControl::NoStore),
        }
    }
}

/// Publish's five `409`s (§5.11), each answered with the token of its
/// name and a REQUIRED answer body.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PublishConflict {
    /// The candidate does not extend the verified head.
    StaleBase,
    /// The operation's accepted candidate is open or landed.
    OperationBound,
    /// Another operation's entry is open.
    NotDecided,
    /// `Granary-Epoch` is not the volume's log epoch.
    EpochMismatch,
    /// The chain head does not verify.
    VolumeDamaged,
}

impl PublishConflict {
    /// The token the `409` carries, which the body's kind must agree with.
    #[must_use]
    pub const fn token(self) -> ErrorToken {
        match self {
            Self::StaleBase => ErrorToken::StaleBase,
            Self::OperationBound => ErrorToken::OperationBound,
            Self::NotDecided => ErrorToken::NotDecided,
            Self::EpochMismatch => ErrorToken::EpochMismatch,
            Self::VolumeDamaged => ErrorToken::VolumeDamaged,
        }
    }
}

/// Every refusal the publish resource answers without an answer body
/// (§5.10, §5.11): each is a status, a token and §8.3's empty body, and
/// every one carries `no-store`.
///
/// Its own type, beside [`StatusRefusal`], so that no refusal the
/// protocol does not define on this resource can be built for it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PublishRefusal {
    /// `400` + `bad-request`: a missing or malformed publish field, or a
    /// conditional request header field §5a.6 refuses.
    BadRequest,
    /// `403` + `no-principal`.
    NoPrincipal,
    /// `403` + `not-enrolled`.
    NotEnrolled,
    /// `503` + `enrollment-unavailable`, with no `Retry-After`.
    EnrollmentUnavailable,
    /// `429` + `rate-limited`, with its `Retry-After` in delay-seconds.
    RateLimited {
        /// The `Retry-After` value, in seconds.
        retry_after: u32,
    },
    /// `400` + `invalid-candidate`.
    InvalidCandidate,
    /// `400` + `missing-reference`.
    MissingReference,
    /// `400` + `invalid-reference`.
    InvalidReference,
    /// `413` + `publish-work-limit`.
    PublishWorkLimit,
    /// `413` + `too-large`: the candidate is over the body bound, or longer
    /// than the log can hold.
    TooLarge,
    /// `404` + `no-log`: the authority serves the volume, and it has no
    /// log.
    NoLog,
    /// `404` + `unknown-volume`: the authority does not serve the volume.
    UnknownVolume,
    /// `405` + `method-not-allowed`, with `Allow: POST`.
    MethodNotAllowed,
    /// `500` + `internal`.
    Internal,
    /// `503` + `unavailable`: load shedding or admission evidence unavailable.
    Unavailable,
    /// `503` + `fenced`, with no `Retry-After`.
    Fenced,
    /// `503` + `stopped`, with no `Retry-After`.
    Stopped,
}

impl PublishRefusal {
    /// The status and token this refusal answers with.
    #[must_use]
    pub const fn answer(self) -> (Status, ErrorToken) {
        match self {
            Self::BadRequest => (Status::BadRequest, ErrorToken::BadRequest),
            Self::NoPrincipal => (Status::Forbidden, ErrorToken::NoPrincipal),
            Self::NotEnrolled => (Status::Forbidden, ErrorToken::NotEnrolled),
            Self::EnrollmentUnavailable => (
                Status::ServiceUnavailable,
                ErrorToken::EnrollmentUnavailable,
            ),
            Self::RateLimited { .. } => (Status::TooManyRequests, ErrorToken::RateLimited),
            Self::InvalidCandidate => (Status::BadRequest, ErrorToken::InvalidCandidate),
            Self::MissingReference => (Status::BadRequest, ErrorToken::MissingReference),
            Self::InvalidReference => (Status::BadRequest, ErrorToken::InvalidReference),
            Self::PublishWorkLimit => (Status::ContentTooLarge, ErrorToken::PublishWorkLimit),
            Self::TooLarge => (Status::ContentTooLarge, ErrorToken::TooLarge),
            Self::NoLog => (Status::NotFound, ErrorToken::NoLog),
            Self::UnknownVolume => (Status::NotFound, ErrorToken::UnknownVolume),
            Self::MethodNotAllowed => (Status::MethodNotAllowed, ErrorToken::MethodNotAllowed),
            Self::Internal => (Status::InternalServerError, ErrorToken::Internal),
            Self::Unavailable => (Status::ServiceUnavailable, ErrorToken::Unavailable),
            Self::Fenced => (Status::ServiceUnavailable, ErrorToken::Fenced),
            Self::Stopped => (Status::ServiceUnavailable, ErrorToken::Stopped),
        }
    }
}

/// Every refusal the volume status answers (§5.10, §5.12): each is a
/// status, a token and §8.3's empty body, and every one carries
/// `no-store`. A read needs no principal and is charged nothing (§3.2
/// rule 6), so no principal refusal and no `429` is among them.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StatusRefusal {
    /// `400` + `bad-request`: a conditional request header field §5a.6
    /// refuses.
    BadRequest,
    /// `404` + `no-log`: the authority serves the volume, and it has no
    /// log.
    NoLog,
    /// `404` + `unknown-volume`: the authority does not serve the volume.
    UnknownVolume,
    /// `405` + `method-not-allowed`, with `Allow: GET`.
    MethodNotAllowed,
    /// `500` + `internal`.
    Internal,
    /// `503` + `unavailable`: load shedding or admission evidence unavailable.
    Unavailable,
    /// `503` + `fenced`.
    Fenced,
    /// `503` + `stopped`.
    Stopped,
}

impl StatusRefusal {
    /// The status and token this refusal answers with.
    #[must_use]
    pub const fn answer(self) -> (Status, ErrorToken) {
        match self {
            Self::BadRequest => (Status::BadRequest, ErrorToken::BadRequest),
            Self::NoLog => (Status::NotFound, ErrorToken::NoLog),
            Self::UnknownVolume => (Status::NotFound, ErrorToken::UnknownVolume),
            Self::MethodNotAllowed => (Status::MethodNotAllowed, ErrorToken::MethodNotAllowed),
            Self::Internal => (Status::InternalServerError, ErrorToken::Internal),
            Self::Unavailable => (Status::ServiceUnavailable, ErrorToken::Unavailable),
            Self::Fenced => (Status::ServiceUnavailable, ErrorToken::Fenced),
            Self::Stopped => (Status::ServiceUnavailable, ErrorToken::Stopped),
        }
    }
}

/// A strong `entity-tag` (RFC 9110 §8.8.3), validated in its
/// constructor.
///
/// §5.8 makes the hint's `ETag` REQUIRED **and strong**, and calls the
/// stored hint object untrusted in the strongest sense Phase 1 has:
/// anyone who can write the bucket can write it. Nothing downstream
/// re-checks the value — an adapter writes it verbatim — so the grammar
/// is checked once, here, and a value that is not a strong `entity-tag`
/// never becomes an `Outcome` field. A `CR` or an `LF` in a field value
/// is header injection, and this is the boundary that stops one.
#[derive(Debug, PartialEq, Eq)]
pub struct ETag(String);

impl ETag {
    /// The complete `ETag` field value, or `None` when it is not a strong
    /// `entity-tag`.
    ///
    /// The grammar is RFC 9110 §8.8.3's `DQUOTE *etagc DQUOTE`, where
    /// `etagc` is `%x21 / %x23-7E / obs-text` — note `%x22` (`"`) is
    /// excluded, which is why a value cannot be quoted twice. The weak
    /// form `W/"…"` fails it, because §5.8 requires a strong validator.
    ///
    /// **One deliberate narrowing of that ABNF: `""` is rejected**, even
    /// though `*etagc` admits zero characters. §5.8 requires the `ETag`
    /// to CHANGE whenever the hint's seq changes, and an empty validator
    /// cannot — it is also exactly what a store yields when the backend
    /// reported no entity-tag at all, which is the case where the server
    /// has no validator rather than a short one. Emitting it would
    /// revalidate forever and pin every reader to a dead seq.
    ///
    /// **`None` is the caller's `500`.** §5.8 makes the field REQUIRED on
    /// the hint's `200`, so a server that cannot spell one has failed;
    /// it is never a `4xx`, and it is never a panic. A store's version
    /// token is opaque and carries no quoting of its own on some
    /// backends and its own quoting on others, so a caller holding one
    /// decides which of those it has before wrapping it — quoting an
    /// already-quoted token puts a `"` inside the tag and is rejected
    /// here.
    #[must_use]
    pub fn new(value: String) -> Option<Self> {
        // Two DISTINCT quotes: `strip_suffix` on what is left after the
        // prefix, so the one-byte value `"` is not read as both.
        let inner = value.as_bytes().strip_prefix(b"\"")?.strip_suffix(b"\"")?;
        if inner.is_empty() {
            return None;
        }
        if !inner
            .iter()
            .all(|byte| matches!(byte, 0x21 | 0x23..=0x7E | 0x80..=0xFF))
        {
            return None;
        }
        Some(Self(value))
    }

    /// The complete field value, as an adapter writes it.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// The extent a `206` declares, in the units `Content-Range` uses.
///
/// Both positions are **inclusive** (RFC 9110 §14.1.2). The fields are
/// private and the only constructor is [`Outcome::bin_range`], which
/// derives them from the body it is given — so a declared extent that
/// disagrees with the delivered one cannot be built, which is what §7.2
/// forbids in the direction that matters ("a body shorter than its own
/// declared extent contradicts the field that describes it").
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Extent {
    first: u64,
    last: u64,
}

impl Extent {
    /// The first byte position of the served extent, inclusive.
    #[must_use]
    pub const fn first(self) -> u64 {
        self.first
    }

    /// The last byte position of the served extent, **inclusive**.
    #[must_use]
    pub const fn last(self) -> u64 {
        self.last
    }
}

// ------------------------------------------------------- the seq body

/// Digits in a `max-seq` or hint body (§5.7, §5.8).
const SEQ_DIGITS: usize = 20;

const _: () = {
    // 20 is exactly what `u64::MAX` needs (`18446744073709551615`), so
    // the padding is lossless and the fixed-width parse on the other
    // side stays total. One fewer would truncate a legitimate seq.
    assert!(u64::MAX.ilog10() as usize + 1 == SEQ_DIGITS);
};

/// Render a seq as §5.7's and §5.8's body: exactly [`SEQ_DIGITS`] ASCII
/// digits, zero-padded, no newline, no sign.
///
/// **This rendering and this width MUST agree with `granary-core`'s
/// `rootstore::format_hint_body` and `rootstore::SEQ_KEY_DIGITS`**, which
/// are what the client parses and what the object-store key layout uses.
/// This crate takes no dependency on `granary-core`, so the agreement
/// cannot be asserted from here; the task that adds the dependency owes
/// a test comparing the two over a value set that includes `u64::MAX`.
fn seq_body(seq: NonZeroU64) -> Vec<u8> {
    let value = seq.get();
    format!("{value:0SEQ_DIGITS$}").into_bytes()
}

// --------------------------------------------------------------- outcome

/// The status/token pair, and the only place one can be assembled.
///
/// **A private module is what does the work here, and nothing else could
/// have.** The fields of [`Answer`] are private to this module, so the
/// rest of this file can name the type and cannot build one field by
/// field. The struct-update idiom the constructors below use six times
/// over — `Self { error: Some(…), ..Self::success(…) }` — therefore stops
/// compiling instead of putting a `Granary-Error` on a `200`, which it did
/// silently while `error` was a field of [`Outcome`].
mod answer {
    use super::{ErrorToken, Status, SuccessStatus};

    /// A status together with the `Granary-Error` token §8.2 requires on
    /// it, if any.
    ///
    /// The invariant is total over the two constructors: the token is
    /// present on exactly the statuses [`Status::is_refusal`] classifies
    /// as refusals. [`Answer::success`] cannot NAME a refusal status —
    /// its parameter is [`SuccessStatus`] — and [`Answer::refused`] drops
    /// a token offered with a success status.
    ///
    /// **What this type does not decide is WHICH token.** §8.2 requires
    /// *a* token on a `4xx`/`5xx` and says nothing about which, so
    /// `refused(Status::NotFound, ErrorToken::AlreadyExists)` — a `404` +
    /// `already-exists` pair no §5.x row defines — is still a legal
    /// `Answer`. Which token belongs with which status is §8.1 and §5.5
    /// semantics, and what holds it is the nineteen-row table in
    /// `every_refusal_pairs_its_status_with_exactly_one_token`, not this
    /// type.
    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub(super) struct Answer {
        status: Status,
        error: Option<ErrorToken>,
    }

    impl Answer {
        /// A success: a status §8.2 carries no token on, and nothing else.
        pub(super) const fn success(status: SuccessStatus) -> Self {
            Self {
                status: status.status(),
                error: None,
            }
        }

        /// A refusal: a status and exactly one token, always together.
        ///
        /// The STATUS decides in both directions — a token offered with a
        /// status §8.2 does not scope the field to is not carried.
        pub(super) const fn refused(status: Status, error: ErrorToken) -> Self {
            Self {
                status,
                error: if status.is_refusal() {
                    Some(error)
                } else {
                    None
                },
            }
        }

        /// The status.
        pub(super) const fn status(self) -> Status {
            self.status
        }

        /// The token, present on exactly the refusals.
        pub(super) const fn error(self) -> Option<ErrorToken> {
            self.error
        }
    }
}

use answer::Answer;

/// The complete response a handler answers with.
///
/// Every field is private and every constructor names one row of a §5.x
/// status table, so the per-response metadata §6 and §11 fix is not a
/// parameter a caller supplies — it is a property of the row, decided
/// here. A `206` cannot be built without its extent, a bin response
/// cannot be given an `ETag`, and a `204` cannot be given a body.
///
/// Bodies are **owned**. The seam hands back an owned `Vec<u8>`
/// (`get_bin_range` and `get_meta` are frozen that way in `granary-core`
/// and shared with the client and the simulator), and an `Outcome` MOVES
/// it: same pointer, same capacity, no copy. There is deliberately **no
/// `Clone`** — the body reaches `BIN_MAX_BYTES` on the request path, and
/// a derive nobody calls is a heap copy of a quarter of a gigabyte that
/// no reviewer would see at the call site.
#[derive(Debug, PartialEq, Eq)]
pub struct Outcome {
    answer: Answer,
    content_type: Option<ContentType>,
    cache_control: Option<CacheControl>,
    allow: Option<Allow>,
    etag: Option<ETag>,
    extent: Option<Extent>,
    retry_after: Option<u32>,
    body: Vec<u8>,
}

impl Outcome {
    /// **The one place a status/token pair is built** — the [`Answer`]
    /// module's two constructors, reached only through `success` and
    /// `refused` below. §8.2's rule (a `Granary-Error` on every refusal
    /// and on nothing else) is a property of that type rather than of a
    /// list someone remembered to extend, because the pair's fields are
    /// private to a module this one cannot reach into.
    ///
    /// **What that claim covers, exactly.** Every constructor here builds
    /// its remaining fields with the struct-update idiom, so this is NOT
    /// the one place an `Outcome` is built and the comment must not say
    /// it is. Status and token presence are represented together by
    /// `Answer`, rather than by independently writable fields here.
    ///
    /// **What it does not cover:** the wrong token FOR a status, such as
    /// a `404` carrying `already-exists`. §8.2 requires only that a
    /// refusal carry a token; which one is §8.1/§5.5 semantics and is
    /// held by the nineteen-row refusal table in the tests, not here.
    const fn from_answer(answer: Answer) -> Self {
        Self {
            answer,
            content_type: None,
            cache_control: None,
            allow: None,
            etag: None,
            extent: None,
            retry_after: None,
            body: Vec::new(),
        }
    }

    /// A success: a status §8.2 carries no token on, and nothing else.
    const fn success(status: SuccessStatus) -> Self {
        Self::from_answer(Answer::success(status))
    }

    /// A refusal: a status and exactly one token, always together.
    const fn refused(status: Status, error: ErrorToken) -> Self {
        Self::from_answer(Answer::refused(status, error))
    }

    pub(crate) fn intent(
        status: Status,
        token: Option<ErrorToken>,
        ty: ContentType,
        body: Vec<u8>,
    ) -> Self {
        let base = match token {
            Some(token) => Self::refused(status, token),
            None => Self::success(SuccessStatus::Ok),
        };
        Self {
            content_type: Some(ty),
            body,
            cache_control: Some(CacheControl::NoStore),
            ..base
        }
    }

    pub(crate) const fn intent_refused(status: Status, token: ErrorToken) -> Self {
        let mut result = Self::refused(status, token);
        result.cache_control = Some(CacheControl::NoStore);
        result
    }

    // -- successes -------------------------------------------------------

    /// `201`, no content — a novel bin or meta object was stored (§5.1,
    /// §5.3), or a root was created at a free seq (§5.5).
    #[must_use]
    pub const fn created() -> Self {
        Self::success(SuccessStatus::Created)
    }

    /// `200`, no content — a content-addressed `PUT` found its object
    /// already present (§5.1, §5.3).
    ///
    /// An existing object is success, never an error: the occupant holds
    /// the same bytes the caller was about to write. The `201`/`200`
    /// split is the seam's novelty `bool` and carries no other meaning.
    #[must_use]
    pub const fn already_present() -> Self {
        Self::success(SuccessStatus::Ok)
    }

    /// `204`, no content — the hint was written (§5.9).
    ///
    /// One success status, whether the hint was created or replaced: the
    /// seam cannot tell those apart, and `204` asserts only that the
    /// request succeeded, which is true on both paths.
    #[must_use]
    pub const fn hint_written() -> Self {
        Self::success(SuccessStatus::NoContent)
    }

    /// `200` + the stored meta bytes (§5.4).
    #[must_use]
    pub fn meta(body: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::Meta),
            body,
            ..Self::success(SuccessStatus::Ok)
        }
    }

    /// `200` + the stored root bytes, byte for byte (§5.6).
    ///
    /// Carries the immutable directive, which §6 makes a MAY on a
    /// numbered root: the resource is append-only, so the year-long
    /// freshness lifetime states nothing false. No `ETag` — §6 makes one
    /// OPTIONAL and inert here, and emitting none avoids a second place
    /// to get validator policy right.
    #[must_use]
    pub fn root(body: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::Root),
            cache_control: Some(CacheControl::Immutable),
            body,
            ..Self::success(SuccessStatus::Ok)
        }
    }

    /// `200` + the head's seq as exactly 20 ASCII digits (§5.7).
    ///
    /// **Takes the VALUE, not the bytes.** §5.7 fixes the body as exactly
    /// 20 zero-padded ASCII digits with no newline and states that "the
    /// server MUST NOT answer `0`" as a MUST both sides enforce, so
    /// neither the shape nor the forbidden value is left to a caller: a
    /// [`NonZeroU64`] cannot be `0`, and `seq_body` is the only thing
    /// that writes the digits.
    ///
    /// **Where the `0` case lands now.** `RootStore::max_seq` answers
    /// `Ok(Some(seq))` with a plain `u64`, so its caller converts —
    /// `NonZeroU64::new(seq)` — and a `None` there means the store named
    /// seq `0` as a head, which §5.7 says cannot be a head at all. That
    /// is a server-side fault and not a statement about the request, so
    /// the answer is [`Outcome::internal`]. It is never a panic and never
    /// a `4xx`. (`Ok(None)` — the volume simply has no roots — is the
    /// separate `404` + `not-found` row, and is not this case.)
    #[must_use]
    pub fn max_seq(seq: NonZeroU64) -> Self {
        Self {
            content_type: Some(ContentType::Text),
            cache_control: Some(CacheControl::NoStore),
            body: seq_body(seq),
            ..Self::success(SuccessStatus::Ok)
        }
    }

    /// `200` + the hint as exactly 20 ASCII digits, with its REQUIRED
    /// strong `ETag` (§5.8).
    ///
    /// Takes the value for the same reason [`Outcome::max_seq`] does,
    /// and §5.8 adds one of its own: a hint body of `0` MUST degrade to
    /// `Missing`, so it is not a body this endpoint may serve.
    ///
    /// **Where the `0` case lands now.** `RootStore::read_hint` answers
    /// `Ok(Current { seq, token })` with a plain `u64`; a caller whose
    /// `NonZeroU64::new(seq)` is `None` holds a stored hint of `0`, and
    /// §5.8's answer to that is `Ok(Missing)` — on the wire, `404` +
    /// `not-found` with `no-cache` (the missing-hint response), which §8.1 maps back to
    /// `Missing`. Not a `5xx`, and not any other `4xx`: §5.8 forbids
    /// both on account of the stored body's shape.
    ///
    /// The `ETag` is opaque — the adapter writes it verbatim, and
    /// nothing derives, parses or compares it against anything but a
    /// token the store gave it — but its GRAMMAR is not opaque, which is
    /// why the parameter is an [`ETag`] and not a `String`.
    #[must_use]
    pub fn hint(seq: NonZeroU64, etag: ETag) -> Self {
        Self {
            content_type: Some(ContentType::Text),
            cache_control: Some(CacheControl::NoCache),
            etag: Some(etag),
            body: seq_body(seq),
            ..Self::success(SuccessStatus::Ok)
        }
    }

    /// `304`, no content, carrying the same `ETag` the `200` would have
    /// carried (§5.8, §6).
    ///
    /// Reachable only when the hint exists and its validator matches: a
    /// volume with no hint object answers `404` even under the
    /// conditional (§5a.6).
    #[must_use]
    pub fn hint_not_modified(etag: ETag) -> Self {
        Self {
            cache_control: Some(CacheControl::NoCache),
            etag: Some(etag),
            ..Self::success(SuccessStatus::NotModified)
        }
    }

    /// `206` + the served bytes and the extent they occupy (§5.2, §7.2).
    ///
    /// The extent is DERIVED from `body`, never declared: `last` is
    /// `first_pos + body.len() - 1`, so the declared extent is the
    /// delivered extent by construction. A short read therefore narrows
    /// the extent honestly rather than leaving a false one behind.
    ///
    /// Answers `None` for an empty body — an empty read is never a
    /// success on this seam, and a zero-width extent has no valid
    /// `Content-Range` — and for the arithmetic overflow a `first_pos`
    /// near `u64::MAX` would cause. Both are the caller's `500`: neither
    /// is a statement about the request.
    #[must_use]
    pub fn bin_range(first_pos: u64, body: Vec<u8>) -> Option<Self> {
        let width = u64::try_from(body.len()).ok()?;
        // `last` is inclusive, so a one-byte body ends where it starts.
        let last = first_pos.checked_add(width.checked_sub(1)?)?;
        Some(Self {
            content_type: Some(ContentType::Bin),
            cache_control: Some(CacheControl::Immutable),
            extent: Some(Extent {
                first: first_pos,
                last,
            }),
            body,
            ..Self::success(SuccessStatus::PartialContent)
        })
    }

    /// `200` + a landed or lost publish answer (§5.11).
    ///
    /// The body is the encoded answer, whose kind the caller has chosen to
    /// agree with the `200`; `no-store`, as on every publish response.
    #[must_use]
    pub fn publish_settled(answer: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::AuthorityAnswer),
            cache_control: Some(CacheControl::NoStore),
            body: answer,
            ..Self::success(SuccessStatus::Ok)
        }
    }

    /// `202` + an accepted or open publish answer (§5.11): the decision is
    /// durable, and the publication is pending.
    #[must_use]
    pub fn publish_pending(answer: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::AuthorityAnswer),
            cache_control: Some(CacheControl::NoStore),
            body: answer,
            ..Self::success(SuccessStatus::Accepted)
        }
    }

    /// `200` + the volume status (§5.12), answered from the authority's
    /// snapshot; `no-store`.
    #[must_use]
    pub fn volume_status(status: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::VolumeStatus),
            cache_control: Some(CacheControl::NoStore),
            body: status,
            ..Self::success(SuccessStatus::Ok)
        }
    }

    // -- refusals --------------------------------------------------------
    //
    // §8.2 makes `Granary-Error` a MUST on every 4xx/5xx the application
    // layer generates, so each of these is a status AND exactly one
    // token, paired here rather than at the call site. The pairs are the
    // whole of §5.1–§5.10; there is no constructor for a pair the
    // protocol does not define.
    //
    // None carries a body. §8.3 makes one a MAY, and §8.4 forbids
    // relaying the diagnostic text a refusal actually has — a store key
    // in particular — so declining is the answer that cannot leak.
    //
    // Generic seam refusals carry no cache directive. Max-seq and hint
    // misses carry their resource directives (§6). Publish and status answer
    // refusals through `publish_refused` and `status_refused`, which carry
    // `no-store` and admit only the refusals §5.11 and §5.12 define; the
    // one refusal both kinds share by construction, the `405`, takes its
    // directive from the resource.

    /// `404` + `not-found` — the addressed object is absent from a
    /// resource this server serves (§5.2, §5.4, §5.6, §5.7, §5.8).
    ///
    /// On `GET root`, `GET hint` and `GET max-seq` a client maps this to
    /// a SUCCESS, and the token is what makes that safe: a `404` from a
    /// proxy or a misrouted path carries no token and must never become
    /// "the volume is empty" (§8.1).
    #[must_use]
    pub const fn not_found() -> Self {
        Self::refused(Status::NotFound, ErrorToken::NotFound)
    }

    /// `404` + `not-found` for a volume without roots, with `no-store` (§5.7, §6).
    pub(crate) const fn max_seq_empty() -> Self {
        let mut empty = Self::not_found();
        empty.cache_control = Some(CacheControl::NoStore);
        empty
    }

    /// `404` + `not-found` for a missing hint, with `no-cache` (§5.8, §6).
    pub(crate) const fn hint_missing() -> Self {
        let mut missing = Self::not_found();
        missing.cache_control = Some(CacheControl::NoCache);
        missing
    }

    /// `404` + `unknown-target` — the target is not one of §4.2's
    /// resources (§4.3, §5.10). **Never** a success mapping.
    #[must_use]
    pub const fn unknown_target() -> Self {
        Self::refused(Status::NotFound, ErrorToken::UnknownTarget)
    }

    /// `409` + `already-exists` — the seq is occupied (§5.5).
    #[must_use]
    pub const fn already_exists() -> Self {
        Self::refused(Status::Conflict, ErrorToken::AlreadyExists)
    }

    /// `400` + `address-mismatch` — the body's hash is not the address it
    /// was sent to (§5.1, §5.3).
    #[must_use]
    pub const fn address_mismatch() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::AddressMismatch)
    }

    /// `400` + `verify-failed` — a grain inside a bin failed its hash
    /// check (§5.1).
    #[must_use]
    pub const fn verify_failed() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::VerifyFailed)
    }

    /// `400` + `layout-invalid` — a bin violated a layout invariant
    /// (§5.1).
    #[must_use]
    pub const fn layout_invalid() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::LayoutInvalid)
    }

    /// `400` + `bad-range` — the `Range` field is absent, malformed,
    /// multi-part, or a form v1 does not accept (§7.1).
    #[must_use]
    pub const fn bad_range_form() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::BadRange)
    }

    /// `416` + `bad-range` — the range's `first-pos` is at or past the
    /// end of every object that could be at that address (§7.3).
    ///
    /// The form was accepted and the range is provably unsatisfiable from
    /// a frozen constant, before the store was touched. It never means
    /// "unsupported form" and never means "the store said no": a
    /// `Backend` error from `get_bin_range` is `500`, because the seam
    /// cannot tell an unsatisfiable range from an outage (§5.2).
    ///
    /// Carries no `Content-Range`: §7.3's grammar has no `*/*` form, so
    /// the field could only be filled by inventing the object's length.
    #[must_use]
    pub const fn range_not_satisfiable() -> Self {
        Self::refused(Status::RangeNotSatisfiable, ErrorToken::BadRange)
    }

    /// `400` + `extent-too-wide` — the mapped `len` exceeds the server's
    /// declared maximum extent (§7.1). Refused whole, never truncated,
    /// decided without the store.
    ///
    /// Minted by the admission gate at step 6, on the mapped `len` and
    /// before the store is touched. `get_bin_range` applies no extent
    /// policy of its own and must not: §7.1 refuses the ask WHOLE, and
    /// a cap in the handler could only narrow an extent the gate had
    /// already admitted.
    #[must_use]
    pub const fn extent_too_wide() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::ExtentTooWide)
    }

    /// `400` + `bad-request` — anything else this profile rejects,
    /// including a hint body that is not exactly 20 digits (§5.9) and
    /// every conditional request header field §5a.6 refuses.
    #[must_use]
    pub const fn bad_request() -> Self {
        Self::refused(Status::BadRequest, ErrorToken::BadRequest)
    }

    /// `405` + `method-not-allowed`, with the target resource's own
    /// method set (§4.2, RFC 9110 §15.5.6).
    ///
    /// Takes the RESOURCE, not the field value. §4.2 fixes `Allow` per
    /// resource, so letting a caller pass the value would let a handler
    /// advertise `PUT` on a read-only resource with nothing able to
    /// notice; see [`Resource::allow`].
    #[must_use]
    pub const fn method_not_allowed(resource: Resource) -> Self {
        // Assigned rather than written with `..Self::refused(…)`: struct
        // update would DROP the funnel's remainder, and dropping a `Vec`
        // is not a const operation. Going through the funnel is what
        // matters, and this does.
        let mut refusal = Self::refused(Status::MethodNotAllowed, ErrorToken::MethodNotAllowed);
        refusal.allow = Some(resource.allow());
        refusal.cache_control = resource.refusal_cache_control();
        refusal
    }

    /// `413` + `too-large` — the body exceeds the cap for its object kind
    /// (§5a.1).
    #[must_use]
    pub const fn too_large() -> Self {
        Self::refused(Status::ContentTooLarge, ErrorToken::TooLarge)
    }

    /// `500` + `internal` — the server failed (§5.10).
    #[must_use]
    pub const fn internal() -> Self {
        Self::refused(Status::InternalServerError, ErrorToken::Internal)
    }

    /// `503` + `unavailable` — the server is shedding load (§5.10).
    #[must_use]
    pub const fn unavailable() -> Self {
        Self::refused(Status::ServiceUnavailable, ErrorToken::Unavailable)
    }

    /// `403` + `no-principal` — with an authority configured, a seam write
    /// on an anonymous connection (§3.2 rule 4), decided before the body.
    #[must_use]
    pub const fn no_principal() -> Self {
        Self::refused(Status::Forbidden, ErrorToken::NoPrincipal)
    }

    /// `403` + `not-enrolled` — a seam write on a connection whose
    /// certificate is not enrolled, or no longer is (§3.2 rules 2, 4).
    #[must_use]
    pub const fn not_enrolled() -> Self {
        Self::refused(Status::Forbidden, ErrorToken::NotEnrolled)
    }

    /// `503` + `enrollment-unavailable` — a certificate-bearing seam write
    /// while the enrollment set fails its check, cannot be read, or is
    /// missing (§3.2 rule 2). No `Retry-After`.
    #[must_use]
    pub const fn enrollment_unavailable() -> Self {
        Self::refused(
            Status::ServiceUnavailable,
            ErrorToken::EnrollmentUnavailable,
        )
    }

    /// `403` + `authority-managed` — a `PUT root` to a volume the authority
    /// serves (§5.5), decided after the principal, before the principal's
    /// controls and before the body.
    #[must_use]
    pub const fn authority_managed() -> Self {
        Self::refused(Status::Forbidden, ErrorToken::AuthorityManaged)
    }

    /// `429` + `rate-limited`, carrying `Retry-After: {retry_after}` in
    /// delay-seconds — a principal-bearing seam request over its
    /// principal's rate or in-flight cap (§3.2 rule 7).
    #[must_use]
    pub const fn rate_limited(retry_after: u32) -> Self {
        let mut refusal = Self::refused(Status::TooManyRequests, ErrorToken::RateLimited);
        refusal.retry_after = Some(retry_after);
        refusal
    }

    /// `409` + one of publish's five tokens, with its REQUIRED answer body
    /// (§5.11, §8.3's one exception); `no-store`.
    #[must_use]
    pub fn publish_conflict(conflict: PublishConflict, answer: Vec<u8>) -> Self {
        Self {
            content_type: Some(ContentType::AuthorityAnswer),
            cache_control: Some(CacheControl::NoStore),
            body: answer,
            ..Self::refused(Status::Conflict, conflict.token())
        }
    }

    /// A refusal on the publish resource (§5.11): its status and token,
    /// no body, `no-store` whatever the refusal, `Allow: POST` on its
    /// `405`, and `Retry-After` on its `429` only.
    #[must_use]
    pub const fn publish_refused(refusal: PublishRefusal) -> Self {
        let (status, token) = refusal.answer();
        let mut outcome = Self::refused(status, token);
        outcome.cache_control = Some(CacheControl::NoStore);
        match refusal {
            PublishRefusal::MethodNotAllowed => {
                outcome.allow = Some(Resource::Publish.allow());
            }
            PublishRefusal::RateLimited { retry_after } => {
                outcome.retry_after = Some(retry_after);
            }
            PublishRefusal::BadRequest
            | PublishRefusal::NoPrincipal
            | PublishRefusal::NotEnrolled
            | PublishRefusal::EnrollmentUnavailable
            | PublishRefusal::InvalidCandidate
            | PublishRefusal::MissingReference
            | PublishRefusal::InvalidReference
            | PublishRefusal::PublishWorkLimit
            | PublishRefusal::TooLarge
            | PublishRefusal::NoLog
            | PublishRefusal::UnknownVolume
            | PublishRefusal::Internal
            | PublishRefusal::Unavailable
            | PublishRefusal::Fenced
            | PublishRefusal::Stopped => {}
        }
        outcome
    }

    /// A refusal on the volume status (§5.12): its status and token, no
    /// body, `no-store` whatever the refusal, `Allow: GET` on its `405`,
    /// and never a `Retry-After`.
    #[must_use]
    pub const fn status_refused(refusal: StatusRefusal) -> Self {
        let (status, token) = refusal.answer();
        let mut outcome = Self::refused(status, token);
        outcome.cache_control = Some(CacheControl::NoStore);
        if matches!(refusal, StatusRefusal::MethodNotAllowed) {
            outcome.allow = Some(Resource::VolumeStatus.allow());
        }
        outcome
    }

    // -- what an adapter transcribes -------------------------------------

    /// The response status.
    #[must_use]
    pub const fn status(&self) -> Status {
        self.answer.status()
    }

    /// The `Granary-Error` token, present on exactly the refusals.
    #[must_use]
    pub const fn error(&self) -> Option<ErrorToken> {
        self.answer.error()
    }

    /// The `Content-Type`, present on exactly the responses that serve a
    /// representation: `GET meta`, `GET root`, `GET max-seq`, `GET hint`,
    /// the bin `206`, the volume status's `200`, and publish's `200`,
    /// `202` and `409`.
    ///
    /// §11 fixes it per row and makes it a MUST on "every `2xx` response
    /// with a body", so it is carried on those rows whether or not the
    /// stored bytes happen to be empty — the row is what decides, not the
    /// length. The bodyless successes (`201`, `204`, the `304`) and every
    /// refusal carry none.
    #[must_use]
    pub const fn content_type(&self) -> Option<ContentType> {
        self.content_type
    }

    /// The `Cache-Control` directive, where §6 fixes one.
    #[must_use]
    pub const fn cache_control(&self) -> Option<CacheControl> {
        self.cache_control
    }

    /// The `Allow` field, present on exactly the `405`s.
    #[must_use]
    pub const fn allow(&self) -> Option<Allow> {
        self.allow
    }

    /// The `Retry-After` value in delay-seconds, present on exactly the
    /// `429`s (§3.2 rule 7).
    #[must_use]
    pub const fn retry_after(&self) -> Option<u32> {
        self.retry_after
    }

    /// The `ETag`, present on exactly the hint's `200` and `304`.
    ///
    /// Written verbatim: the value is the complete field value, and it
    /// was checked against RFC 9110 §8.8.3's strong `entity-tag` grammar
    /// when the [`ETag`] was built.
    #[must_use]
    pub fn etag(&self) -> Option<&str> {
        self.etag.as_ref().map(ETag::as_str)
    }

    /// The served extent, present on exactly the `206`.
    ///
    /// `Content-Range: bytes {first}-{last}/*`, whose `complete-length`
    /// is literally `*` — the seam supplies no object length, so a server
    /// that filled in a number would be inventing one (§7.2).
    #[must_use]
    pub const fn extent(&self) -> Option<Extent> {
        self.extent
    }

    /// The response content, borrowed. Empty where the response carries
    /// none.
    #[must_use]
    pub fn body(&self) -> &[u8] {
        &self.body
    }

    /// The response content, moved out.
    #[must_use]
    pub fn into_body(self) -> Vec<u8> {
        self.body
    }

    /// What the body's allocation OCCUPIES, which is not what it sends.
    ///
    /// **Capacity, not length, and the difference is the whole reason
    /// this exists.** A response body is moved into the transport
    /// and stays resident until flow control has drained it at the
    /// CLIENT's pace, so a server bounding what it holds has to bound the
    /// allocation rather than the extent. `Bytes::from(Vec<u8>)` reuses
    /// the buffer as it is and shrinks only on an exact `len == capacity`
    /// fit, so a buffer that overshot stays overshot for the whole
    /// response — an accounting that read `len()` would under-count by
    /// however much the producer's growth curve happened to overshoot,
    /// and under-counting is the failure mode a byte budget cannot have.
    ///
    /// The seams this crate reads from now hand back exactly-sized
    /// buffers, so the two figures agree in practice; they agree because
    /// something makes them, not by construction, and this is the number
    /// that is true either way.
    #[must_use]
    pub fn body_capacity(&self) -> usize {
        self.body.capacity()
    }
}

