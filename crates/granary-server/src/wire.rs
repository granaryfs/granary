//! The wire vocabulary the handlers answer in.
//!
//! [`Status`] lists the statuses the server generates, [`ErrorToken`] names the
//! `Granary-Error` tokens, and [`Resource`] identifies the ten request targets.
//! Handlers return an [`Outcome`] with the response status, headers and body.
//!
//! The HTTP adapter routes publish, volume status and intent operations to the
//! configured authority. With authority routing disabled, those targets are
//! unknown. The store-only [`crate::dispatch`] handles the nine store operations
//! and returns `404` with `unknown-target` for authority operations.
//!
//! **Everything an adapter needs is on the [`Outcome`], and an adapter
//! DECIDES NOTHING.** Transcribing one is total and mechanical:
//!
//! - the status line is [`Outcome::status`];
//! - `Granary-Error` is [`Outcome::error`], present on exactly the
//!   refusals;
//! - `Content-Type` is [`Outcome::content_type`], `Cache-Control` is
//!   [`Outcome::cache_control`], `ETag` is [`Outcome::etag`] and `Allow`
//!   is [`Outcome::allow`], each present on exactly the responses that
//!   carry it;
//! - `Content-Range` is `bytes {first}-{last}/*` from [`Outcome::extent`],
//!   whose `complete-length` is literally `*` (§7.2);
//! - `Retry-After` is [`Outcome::retry_after`] in delay-seconds, present on
//!   exactly the `429`s (§3.2);
//! - the content is [`Outcome::into_body`], and `Content-Length` is its
//!   length.
//!
//! An adapter MUST NOT add a field this type does not carry. Three are
//! worth naming because a well-meaning adapter would reach for them:
//! `Vary` is forbidden outright (§5a.5), `Accept-Ranges` is a MAY this
//! server declines and other resources MUST NOT advertise range support
//! (§6), and no bin response carries an `ETag` (§6).
//!
//! **No hyper or `http` type appears here.** Defining the vocabulary
//! rather than borrowing `http::StatusCode` buys the one thing that
//! matters: every closed set of the protocol's is a CLOSED ENUM with a
//! wildcard-free match over it, so a set the protocol does not define is
//! a COMPILE event rather than a value someone can build. That is the
//! shape of every type below without exception — [`Status`],
//! [`ErrorToken`], [`ContentType`], [`CacheControl`], [`Allow`] and
//! [`Resource`] — and the two remaining shapes are the same idea applied
//! to values: [`Extent`] derives itself from the body it describes, and
//! [`ETag`] validates its grammar in its constructor.
//!
//! `scripts/check-protocol-constants.py` checks the error registry and media
//! types against independent compatibility fixtures. It follows each resource
//! through [`Resource::allow`] and each explicit cache directive through its
//! [`Outcome`] constructor, so swapping two rows also fails the check.

use std::num::NonZeroU64;

// ---------------------------------------------------------------- status

/// Declares [`Status`], its numeric rendering and [`Status::GENERATED`]
/// from one list.
///
/// The list is the accept set, and it is the ONLY place a variant can
/// come from: a status added here is registered in `GENERATED` and given
/// its number in the same edit, and a status that is not here cannot be
/// named at all. A second `impl Status` block can add no `412`, because
/// there is no numeric constructor for one to use.
macro_rules! statuses {
    ($( $(#[$doc:meta])* $name:ident = $code:literal; )+) => {
        /// A status a granary server generates on this protocol.
        ///
        /// A CLOSED enum with **no field**, for the reason [`ErrorToken`]
        /// is one: §5.1–§5.10 fix the set, so a status outside it is a
        /// compile event rather than a value. There is no route from a
        /// `u16` to a `Status`, which is what makes an adapter's eventual
        /// `StatusCode::from_u16` unable to fail on anything a handler
        /// produced — strictly more than a private field would give,
        /// because a private field still admits a second `impl` block
        /// naming a code this server never sends.
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum Status {
            $( $(#[$doc])* $name, )+
        }

        impl Status {
            /// Every status this server generates, and no others.
            ///
            /// **`412` and `425` are deliberately absent.** §5.10 lists
            /// both as never generated by a granary server: §5a.6 refuses
            /// conditional request header fields with `400` instead of
            /// evaluating them, so no precondition is left to fail, and
            /// §9.4 leaves `425` to an intermediary. They exist in a
            /// *client's* map only so it stays total for a status
            /// something else supplied. A variant for either would be a
            /// standing claim that the status is reachable from here.
            pub const GENERATED: &[Self] = &[ $( Self::$name ),+ ];

            /// The numeric status.
            ///
            /// The match has no wildcard arm, so a new variant
            /// fails to compile here rather than rendering as something
            /// else.
            #[must_use]
            pub const fn as_u16(self) -> u16 {
                match self {
                    $( Self::$name => $code, )+
                }
            }
        }
    };
}

statuses! {
    /// `200` — a stored object served (§5.4, §5.6, §5.7, §5.8), or a
    /// content-addressed `PUT` that found its object already present
    /// (§5.1, §5.3).
    Ok = 200;
    /// `201` — a novel object stored (§5.1, §5.3) or a seq created
    /// (§5.5).
    Created = 201;
    /// `202` — a publish whose decision is durable and whose publication
    /// is pending: accepted now, or open from an earlier decision (§5.11).
    Accepted = 202;
    /// `204` — the hint was written, created or replaced alike (§5.9).
    NoContent = 204;
    /// `206` — a bin range served (§5.2, §7.2).
    PartialContent = 206;
    /// `304` — the hint's validator still matches (§5.8). The one
    /// endpoint on this profile that can answer it.
    NotModified = 304;
    /// `400` — a request this profile does not define, including a
    /// malformed `Range` and any conditional request header field §5a.6
    /// refuses (§5.10).
    BadRequest = 400;
    /// `403` — with an authority configured, a write without a principal,
    /// or a `PUT root` to a volume the authority serves (§3.2, §5.5).
    Forbidden = 403;
    /// `404` — the addressed object is absent, or the target is not one
    /// of §4.2's resources. The two are told apart by the token, never by
    /// the status (§8.1).
    NotFound = 404;
    /// `405` — the method is not defined for this resource (§4.2).
    MethodNotAllowed = 405;
    /// `409` — the seq is occupied (§5.5), or one of publish's five
    /// refusals, each with its answer body (§5.11).
    Conflict = 409;
    /// `413` — the body exceeds the cap for its object kind (§5a.1).
    ContentTooLarge = 413;
    /// `416` — the range's `first-pos` is at or past `BIN_MAX_BYTES`,
    /// decided before the store is touched (§7.1, §7.3).
    RangeNotSatisfiable = 416;
    /// `429` — a principal-bearing request over its principal's rate or
    /// in-flight cap (§3.2).
    TooManyRequests = 429;
    /// `500` — the server failed (§5.10).
    InternalServerError = 500;
    /// `503` — the server is shedding load (§5.10), or the authority is
    /// fenced or stopped (§5.11, §5.12).
    ServiceUnavailable = 503;
}

impl Status {
    /// Whether §8.2 REQUIRES a `Granary-Error` token on this status.
    ///
    /// §8.2 scopes the field to a `4xx` or `5xx` the application layer
    /// generates and makes it a MUST there, so this predicate is the
    /// whole of the rule and `Outcome` decides the field by asking it —
    /// never by writing a numeric range out a second time.
    ///
    /// No wildcard arm: a new status has to be classified here before it
    /// can be answered at all.
    #[must_use]
    pub const fn is_refusal(self) -> bool {
        match self {
            Self::Ok
            | Self::Created
            | Self::NoContent
            | Self::Accepted
            | Self::PartialContent
            | Self::NotModified => false,
            Self::BadRequest
            | Self::Forbidden
            | Self::NotFound
            | Self::MethodNotAllowed
            | Self::Conflict
            | Self::ContentTooLarge
            | Self::RangeNotSatisfiable
            | Self::TooManyRequests
            | Self::InternalServerError
            | Self::ServiceUnavailable => true,
        }
    }
}

/// The statuses the success arm of [`Outcome`]'s funnel accepts:
/// exactly the rows §8.2 carries no `Granary-Error` on.
///
/// Private, and the funnel's success arm takes NOTHING else — so a
/// refusal status cannot reach a construction that would leave the
/// REQUIRED token off it. That is a compile error rather than a test
/// failure, which is what a hand-listed table of rows could never be.
/// `status` has no wildcard arm.
#[derive(Clone, Copy, Debug)]
enum SuccessStatus {
    /// `200`.
    Ok,
    /// `201`.
    Created,
    /// `204`.
    NoContent,
    /// `202`.
    Accepted,
    /// `206`.
    PartialContent,
    /// `304`.
    NotModified,
}

impl SuccessStatus {
    /// The status itself.
    const fn status(self) -> Status {
        match self {
            Self::Ok => Status::Ok,
            Self::Created => Status::Created,
            Self::NoContent => Status::NoContent,
            Self::Accepted => Status::Accepted,
            Self::PartialContent => Status::PartialContent,
            Self::NotModified => Status::NotModified,
        }
    }
}

// ----------------------------------------------------------- error token

/// A token from the `Granary-Error` registry (§8.2).
///
/// **The registry is CLOSED — "a v1 server MUST NOT invent a token"** —
/// so this enum is closed too: it is deliberately not
/// `#[non_exhaustive]`, because being able to enumerate every token is
/// the whole reason granary-server defines its own vocabulary instead of
/// borrowing one.
///
/// There is deliberately **no `precondition-failed`**. Its absence is a
/// rule rather than an omission: a granary server generates no `412` at
/// all (§5a.6, §5.10), and a token no server may send would be a standing
/// claim that the status is reachable from here.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum ErrorToken {
    /// Ownership or generation was displaced.
    IntentSuperseded,
    /// Another root occupies this generation.
    IntentBound,
    /// The selected row changed.
    IntentChanged,
    /// The selected row is absent.
    IntentAbsent,
    /// The allocator cursor changed.
    IntentCursorChanged,
    /// Ownership epochs are exhausted.
    IntentEpochExhausted,
    /// The principal has exhausted an intent quota.
    IntentQuota,
    /// The addressed object does not exist, at a target this server does
    /// serve.
    NotFound,
    /// The request target is not one of §4.2's resources: a segment
    /// failed its total grammar, or the path is not one this server
    /// serves under its base. **Never** a success mapping (§8.1).
    UnknownTarget,
    /// The seq is occupied (`PUT root` only).
    AlreadyExists,
    /// The body's hash is not the address it was sent to.
    AddressMismatch,
    /// A grain inside a bin failed its hash check.
    VerifyFailed,
    /// A bin violated a layout invariant.
    LayoutInvalid,
    /// The `Range` field is absent, malformed, multi-part, or a form v1
    /// does not accept (`400`); or names a `first-pos` at or past the end
    /// of every object that could be at that address (`416`, §7.3). One
    /// token for two answers, because the status is what separates them.
    BadRange,
    /// An accepted range form maps to a `len` wider than the server's
    /// declared maximum extent (§7.1) — refused whole, never truncated.
    ExtentTooWide,
    /// Anything else about the request this profile rejects, including
    /// any conditional request header field §5a.6 refuses.
    BadRequest,
    /// The method is not defined for this resource.
    MethodNotAllowed,
    /// The body exceeds the cap for its object kind.
    TooLarge,
    /// The server failed.
    Internal,
    /// The server is shedding load.
    Unavailable,
    /// A write endpoint's request arrived on an anonymous connection
    /// (`403`, §3.2).
    NoPrincipal,
    /// A write endpoint's request arrived on a connection whose
    /// certificate is not enrolled, or no longer is (`403`, §3.2).
    NotEnrolled,
    /// A principal-bearing request is over its principal's rate or
    /// in-flight cap (`429`, §3.2).
    RateLimited,
    /// A `PUT root` to a volume the authority serves, where only the
    /// authority writes roots (`403`, §5.5).
    AuthorityManaged,
    /// The candidate is not well formed for the volume (`POST publish`,
    /// `400`).
    InvalidCandidate,
    /// A newly required content reference is absent (`400`).
    MissingReference,
    /// Candidate content failed validation (`400`).
    InvalidReference,
    /// Admission exhausted its work allowance (`413`).
    PublishWorkLimit,
    /// The authority serves the volume, and it has no log (`404`).
    NoLog,
    /// The authority does not serve the volume (`404`).
    UnknownVolume,
    /// The candidate does not extend the verified head (`409`).
    StaleBase,
    /// The operation's accepted candidate is open or landed, and this is
    /// a different candidate (`409`).
    OperationBound,
    /// Another operation's entry is open, so nothing is decided (`409`).
    NotDecided,
    /// `Granary-Epoch` is not the volume's log epoch (`409`).
    EpochMismatch,
    /// The volume's chain head does not verify (`409`).
    VolumeDamaged,
    /// The authority is fenced, and answers again only after a host
    /// reboot (`503`).
    Fenced,
    /// The authority has stopped (`503`).
    Stopped,
    /// A certificate-bearing write arrived while the enrollment set fails
    /// its check, cannot be read, or is missing (`503`, §3.2).
    EnrollmentUnavailable,
}

