use super::{OverlayError, OverlayIo, OverlayReadiness, OverlayStore};
use granary_core::support::{BundleOverlay, BundleRefusal};

impl<P: OverlayIo> OverlayStore<P> {
    pub(crate) fn bundle_failure(&self) -> Option<BundleRefusal> {
        self.bundle_failure
    }

    pub(super) fn record_bundle_failure(&mut self, error: &OverlayError) {
        if let Some(refusal) = error.bundle_refusal() {
            self.bundle_failure = Some(refusal);
        }
    }

    /// Project retained accounting at a completed producer transition.
    pub(crate) fn bundle_projection(&self) -> Result<BundleOverlay, BundleRefusal> {
        if let Some(refusal) = self.bundle_failure {
            return Err(refusal);
        }
        if !self.replayed {
            return Err(BundleRefusal::Unavailable);
        }
        let free_entries = self
            .free_entry_capacity()
            .map_err(|_| BundleRefusal::Unavailable)?;
        let journal = self
            .journal
            .lock()
            .map_err(|_| BundleRefusal::Unavailable)?;
        Ok(BundleOverlay {
            readiness: match self.readiness {
                OverlayReadiness::PendingReconciliation => 1,
                OverlayReadiness::PendingRecovery => 2,
                OverlayReadiness::Ready => 3,
                OverlayReadiness::Poisoned => 4,
            },
            commit_state: journal
                .completion
                .commits
                .values()
                .map(|slot| if slot.landed.is_some() { 2 } else { 1 })
                .max()
                .unwrap_or(0),
            namespace_entries: u64::try_from(self.namespace.entries.len())
                .ok()
                .and_then(|count| count.checked_add(1))
                .ok_or(BundleRefusal::Unavailable)?,
            free_entries,
            cap: self.config.cap,
            staged_files: self.namespace.stages.len() as u64,
            journal_records: self.summary.records,
            charged_bytes: self.summary.charged_bytes,
            reserved_bytes: self.summary.reserved_bytes,
            orphan_bytes: self.summary.orphan_bytes,
            captured_bytes: self.summary.captured_bytes,
            swept_files: self.summary.swept_files,
            swept_bytes: self.summary.swept_bytes,
            journal_bytes: journal.length,
            commit_requested: self.summary.commit_requested,
        })
    }
}

