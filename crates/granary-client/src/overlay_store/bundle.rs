impl OverlayError {
    fn bundle_refusal(&self) -> Option<BundleRefusal> {
        match self {
            Self::Io(_) => Some(BundleRefusal::Unreadable),
            Self::ContentCorrupt => Some(BundleRefusal::Corrupt),
            Self::Refused(reason) => REFUSAL_GROUPS
                .iter()
                .find(|(_, reasons)| reasons.contains(reason))
                .map_or(Some(BundleRefusal::Corrupt), |(refusal, _)| *refusal),
            _ => None,
        }
    }

    pub(crate) fn invalidate_bundle(&self, retained: &mut Result<BundleOverlay, BundleRefusal>) {
        *retained = match self {
            Self::Poisoned => retained.map(|mut summary| {
                summary.readiness = 4;
                summary
            }),
            _ => self.bundle_refusal().map_or(*retained, Err),
        };
    }
}
